-- History of administrator removals.
-- Rows are only added, never changed, because `Adminstrator.reactive()`
-- clears `removeAT` and `removeBy` and would otherwise erase who removed whom.

CREATE TABLE administrator_removal_log
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    -- The administrator the event is about.
    administrator_id BIGINT                                  NOT NULL,
    -- The administrator who did it.
    actor_id         BIGINT                                  NOT NULL,
    event            VARCHAR(30)                             NOT NULL,
    occurred_at      TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    CONSTRAINT pk_administrator_removal_log PRIMARY KEY (id)
);

